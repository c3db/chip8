class Chip8 {
    public:
        uint16_t pc;
        uint16_t i;
        std::stack<uint16_t> stack;
        uint8_t delay_timer;
        uint8_t sound_timer;
        std::vector<uint8_t> registers;
        std::vector<uint8_t> memory;

    public:
        Chip8();

        void cls(); // 00E0
        void jmp(); // 1NNN
        void setVX(); // 6XNN
        void addVX(); // 7XNN
        void setI(); // ANNN
        void draw(); // DXYN
};

